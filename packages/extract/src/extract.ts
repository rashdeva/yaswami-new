/** Правила «что куда» для включённых тем: `тип события — «тема»`. */
export const topicRules = () => TOPIC_RULES.flatMap(([what, topics]) => {
  const topic = topics.find((t) => Object.hasOwn(TOPIC_GUIDES, t));
  return topic ? [`${what} — «${topic}»`] : [];
}).join('; ');
/** Фраза с правилами для подсказки; ни одно правило не подошло — пусто, без оборванного «границы: .». */
export const topicBoundaries = (lead: string) => {
  const rules = topicRules();
  return rules ? `${lead}${rules}.` : '';
};

